#!/usr/bin/env bash
# Regenerate assets/js/search-paths.js, the list of pages the site search indexes.
#
# Docsify's search only indexes pages it can see linked from the sidebar on the
# current page, which on the home page is just the top-level section pages. An
# explicit list makes every page searchable from anywhere.
#
# Run after adding, renaming or removing a page:  ./infra/gen-search-paths.sh
# Skipped: files starting with "_" (sidebars, 404), dot folders, and the pages
# listed in EXCLUDE below.
set -euo pipefail
cd "$(dirname "$0")/.."

EXCLUDE=("pers-content" "LICENSE")
OUT="assets/js/search-paths.js"
mkdir -p "$(dirname "$OUT")"

{
  echo "// GENERATED by infra/gen-search-paths.sh. Do not edit by hand."
  echo "window.PA_SEARCH_PATHS = ["
  find . -name '*.md' -not -path './.*' -not -name '_*' | sed 's|^\./||' | sort | while read -r f; do
    route="/${f%.md}"
    case "$route" in
      /README) route="/" ;;
      */README) route="${route%README}" ;;
    esac
    skip=0
    for e in "${EXCLUDE[@]}"; do [ "$route" = "/$e" ] && skip=1; done
    [ "$skip" = 1 ] || echo "  \"$route\","
  done
  echo "];"
} > "$OUT"

echo "Wrote $OUT ($(grep -c '^  "' "$OUT") pages)"
